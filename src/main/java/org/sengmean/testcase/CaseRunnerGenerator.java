package org.sengmean.testcase;

import org.sengmean.config.ConfigDataProvider;
import org.sengmean.report.CaseIndex;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Writes one clickable launcher per test case into {@code TestCase/run}.
 *
 * <h2>What this is for</h2>
 * The project already has three ways to run a single case, and all three assume the person
 * running it is a developer: {@code ./mvnw test -Dcase=LGN-002} assumes a terminal and the
 * wrapper, {@code -Dtest=LoginTest#method} assumes knowing the Java method name, and the
 * {@code fpr://} handler in {@code tools/run-case.ps1} assumes a registry entry has been
 * installed on that machine. A tester handed the repository has none of those.
 *
 * <p>A {@code .cmd} per case is the fourth way, and the only one that survives being emailed as a
 * zip: double-click {@code LOGIN-001.cmd} and that case runs. It is the shape the sibling UMPay
 * suite uses - {@code TestCase/run/Bills_TC_001.cmd} and its forty siblings - and it is worth
 * having here for the same reason it is worth having there.
 *
 * <h2>Generated, and regenerated on every run</h2>
 * Nothing in {@code TestCase/run} is written by hand. The ids come from {@link CaseIndex}, which
 * reads them out of the {@code @DisplayName} of every case, so the launchers cannot drift from the
 * suites: a case renamed in the IDE renames its launcher on the next run, and a case deleted has
 * its launcher pruned. That is why {@code HtmlReportListener} calls this at the end of a run
 * rather than leaving it as a command somebody has to remember - a generated file you have to ask
 * for is a generated file that is wrong by the time anyone uses it.
 *
 * <p>It can also be run on its own, which is what you want after adding cases but before running
 * anything:
 *
 * <pre>./mvnw exec:java@case-runners</pre>
 *
 * <h2>Each launcher narrows the scan before it filters</h2>
 * {@code -Dcase=} alone works, but Surefire then scans and loads every {@code *Test} class in the
 * project to find the one case. Passing {@code -Dsuite=<the test class>} as well restricts the
 * scan at discovery time, which is the difference between a single case starting in a second and
 * starting in twenty. Both are needed: {@code -Dsuite} chooses the file, {@code -Dcase} chooses
 * the case inside it.
 */
public final class CaseRunnerGenerator {

    /** Where the launchers go. A sibling of the workbook the cases were written from. */
    private static final Path DIR = Path.of(ConfigDataProvider.get("testcase.run.dir", "TestCase/run"));

    /** Windows refuses some of these outright and a shell would misread the rest. */
    private static final String UNSAFE = "[^A-Za-z0-9._-]";

    private CaseRunnerGenerator() {
    }

    public static void main(String[] args) throws IOException {
        int written = generate();
        System.out.println("Wrote " + written + " case launchers to " + DIR.toAbsolutePath());
    }

    /**
     * Rewrites every launcher, prunes the ones no case answers to any more, and refreshes the
     * README that indexes them.
     *
     * @return how many launchers the folder now holds
     */
    public static int generate() throws IOException {
        Map<String, CaseIndex.TestCase> cases = CaseIndex.byId();
        Files.createDirectories(DIR);

        Map<String, String> expected = new LinkedHashMap<>();
        for (Map.Entry<String, CaseIndex.TestCase> entry : cases.entrySet()) {
            String fileName = entry.getKey().replaceAll(UNSAFE, "_") + ".cmd";
            expected.put(fileName, script(entry.getKey(), entry.getValue()));
        }

        for (Map.Entry<String, String> file : expected.entrySet()) {
            write(DIR.resolve(file.getKey()), file.getValue());
        }

        prune(expected.keySet());
        write(DIR.resolve("README.md"), readme(cases));

        return expected.size();
    }

    /**
     * The batch file for one case.
     *
     * <p>{@code cd /d "%~dp0..\..">} rather than relying on the working directory: double-clicking
     * a {@code .cmd} starts it in its own folder, and {@code mvnw.cmd}, {@code Config/} and the
     * report paths are all resolved from the project directory. {@code %~dp0} is where this file
     * is, and two levels up from {@code TestCase\run} is the project.
     */
    private static String script(String id, CaseIndex.TestCase testCase) {
        StringBuilder out = new StringBuilder();
        out.append("@echo off\r\n");
        out.append("rem Runs one Admin_weibo test case by its client case id.\r\n");
        out.append("rem\r\n");
        out.append("rem GENERATED by org.sengmean.testcase.CaseRunnerGenerator, rewritten at the end of\r\n");
        out.append("rem every test run. Edits here are lost. To change how a case is run, change the\r\n");
        out.append("rem generator; to change what this case does, change the test it points at:\r\n");
        out.append("rem   ").append(testCase.selector()).append("\r\n");
        out.append("\r\n");
        out.append("setlocal\r\n");
        out.append("cd /d \"%~dp0..\\..\"\r\n");
        out.append("\r\n");

        if (testCase.createsData()) {
            out.append("echo  *** ").append(id).append(" is tagged creates-data. ***\r\n");
            out.append("echo  It leaves something behind on the test environment - a registered\r\n");
            out.append("echo  account, a locked account, a submitted transaction - that outlives\r\n");
            out.append("echo  the run and that somebody may have to undo. Close this window now\r\n");
            out.append("echo  if that was not the intention.\r\n");
            out.append("echo.\r\n");
            out.append("pause\r\n");
            out.append("\r\n");
        }
        if (testCase.knownDefect()) {
            out.append("echo  Note: ").append(id).append(" is tagged known-defect. It asserts behaviour the\r\n");
            out.append("echo  application does not have yet, so a failure here is expected and is\r\n");
            out.append("echo  not news. See the test's own comment for what it is waiting for.\r\n");
            out.append("echo.\r\n");
            out.append("\r\n");
        }

        out.append("echo Running ").append(id).append(" - ").append(echoSafe(testCase.expected())).append("\r\n");
        out.append("echo.\r\n");
        out.append("\r\n");
        // -Dsuite narrows what Surefire scans; -Dcase picks the case out of it. The quotes matter
        // for neither value here, but they cost nothing and keep the line correct if an id ever
        // grows a character cmd would otherwise treat as a separator.
        out.append("call mvnw.cmd test \"-Dsuite=").append(testCase.suite())
                .append("\" \"-Dcase=").append(id).append("\"\r\n");
        out.append("\r\n");
        out.append("echo.\r\n");
        out.append("if errorlevel 1 (echo   FAILED) else (echo   PASSED)\r\n");
        out.append("echo   Report: docs\\reports\\index.html\r\n");
        out.append("echo.\r\n");
        out.append("echo Press any key to close.\r\n");
        out.append("pause >nul\r\n");
        return out.toString();
    }

    /**
     * Text safe to sit after {@code echo} in a batch file.
     *
     * <p>{@code &}, {@code |}, {@code <} and {@code >} are command separators and redirections to
     * cmd even inside an echo, so a display name containing one would truncate the line or, worse,
     * create a file named after the rest of it. Replaced rather than escaped, because the caret
     * escaping rules differ between a plain line and one inside parentheses and this string only
     * has to be readable.
     */
    private static String echoSafe(String text) {
        String oneLine = text.replaceAll("\\s+", " ").trim();
        String safe = oneLine.replaceAll("[&|<>^%]", "-");
        return safe.length() <= 90 ? safe : safe.substring(0, 87) + "...";
    }

    /** Deletes launchers for cases that no longer exist, leaving anything else alone. */
    private static void prune(java.util.Set<String> keep) throws IOException {
        try (Stream<Path> files = Files.list(DIR)) {
            for (Path file : files.toList()) {
                String name = file.getFileName().toString();
                if (name.endsWith(".cmd") && !keep.contains(name)) {
                    Files.deleteIfExists(file);
                }
            }
        }
    }

    /** The index of what is in the folder, grouped by the suite each case belongs to. */
    private static String readme(Map<String, CaseIndex.TestCase> cases) {
        Map<String, List<Map.Entry<String, CaseIndex.TestCase>>> bySuite = new LinkedHashMap<>();
        for (Map.Entry<String, CaseIndex.TestCase> entry : cases.entrySet()) {
            bySuite.computeIfAbsent(entry.getValue().suite(), suite -> new ArrayList<>()).add(entry);
        }

        StringBuilder out = new StringBuilder();
        out.append("# TestCase/run\n\n");
        out.append("One launcher per automated case. Double-click the `.cmd` for the case you want and\n");
        out.append("it runs on its own, against the environment `Config/config.properties` names.\n\n");
        out.append("**Everything in this folder is generated** by `org.sengmean.testcase.CaseRunnerGenerator`\n");
        out.append("and rewritten at the end of every test run, so it cannot drift from the suites. Edits\n");
        out.append("here are lost. Rebuild it without running anything with:\n\n");
        out.append("```\n./mvnw exec:java@case-runners\n```\n\n");
        out.append("Two tags change what a launcher does before it runs anything:\n\n");
        out.append("- **creates-data** - the case leaves something behind on the test environment that\n");
        out.append("  somebody may have to undo. Its launcher says so and waits for a keypress first.\n");
        out.append("- **known-defect** - the case asserts behaviour the site does not have yet, so a red\n");
        out.append("  result is expected. Its launcher says so.\n\n");
        out.append("| Case | Suite | What it proves | |\n");
        out.append("|---|---|---|---|\n");

        for (Map.Entry<String, List<Map.Entry<String, CaseIndex.TestCase>>> suite : bySuite.entrySet()) {
            for (Map.Entry<String, CaseIndex.TestCase> entry : suite.getValue()) {
                CaseIndex.TestCase testCase = entry.getValue();
                List<String> notes = new ArrayList<>();
                if (testCase.createsData()) {
                    notes.add("creates-data");
                }
                if (testCase.knownDefect()) {
                    notes.add("known-defect");
                }
                out.append("| [`").append(entry.getKey()).append("`](")
                        .append(entry.getKey().replaceAll(UNSAFE, "_")).append(".cmd) | ")
                        .append(suite.getKey()).append(" | ")
                        .append(cell(testCase.expected())).append(" | ")
                        .append(String.join(", ", notes)).append(" |\n");
            }
        }

        out.append("\n").append(cases.size()).append(" cases.\n");
        return out.toString();
    }

    /** A display name with the characters that would break out of a Markdown table removed. */
    private static String cell(String text) {
        return text.replace("|", "\\|").replaceAll("\\s+", " ").trim();
    }

    /**
     * Writes only when the content actually changed.
     *
     * <p>Otherwise every run would restamp forty files that git then reports as modified, which
     * makes a real change to a launcher impossible to spot in a diff and turns `git status` into
     * noise after any test run.
     */
    private static void write(Path file, String content) throws IOException {
        if (Files.exists(file) && content.equals(Files.readString(file, StandardCharsets.UTF_8))) {
            return;
        }
        Files.writeString(file, content, StandardCharsets.UTF_8);
    }
}
