package org.sengmean.page.tool;

import com.microsoft.playwright.Locator;
import com.microsoft.playwright.Page;
import com.microsoft.playwright.options.AriaRole;
import org.sengmean.base.BasePage;
import org.sengmean.page.common.PromptMessage;
import org.sengmean.report.CaseLog;

/**
 * <b>Tool &gt; Notification &gt; Ranking Alerts</b> - the third tab the sheet's {@code SN-ADM-RNK}
 * rows describe, read from the Figma mockup Si gave (Platform project, "version <b>5.1.0</b>" page
 * - a later page than the "version 3.20.0" one Add Member, Rankings and Share Link were read from,
 * frame {@code notification-ranking-alert-settings}, "Tool &gt; Notification &gt; Ranking Alerts tab
 * (On/Off, system-generated title + data card)").
 *
 * <h2>What the frame shows</h2>
 * An intro line: "Title and data card are generated by the system from Membership and Rankings
 * data, in the member's language. Admin only switches each alert On/Off." Then a table headed
 * <b>ALERT</b> / <b>WHEN IT IS SENT (SYSTEM RULE)</b> / <b>DATA CARD SHOWN TO MEMBER</b>, one row
 * per alert - {@link #MEMBERSHIP_UPGRADE}, {@link #REFERRAL_RANKING}, {@link #WITHDRAWAL_RANKING} -
 * each with an On/Off switch, no content field of any kind (the content is system-generated).
 * <b>Save changes</b> / <b>Cancel</b> at the bottom.
 *
 * <h2>Not deployed yet</h2>
 * Measured live on admin-test 2026-10-21: Tool &gt; Notification offers only two tabs, Notification
 * and Record History - no Ranking Alerts. Every locator here is read from the mockup rather than
 * measured, the same caveat {@code RankingListPage} and {@code ShareLinkListPage} carry for their
 * own screens.
 */
public class RankingAlertsSettingsPage extends BasePage {

    public static final String MEMBERSHIP_UPGRADE = "Membership upgrade";
    public static final String REFERRAL_RANKING = "Referral Ranking";
    public static final String WITHDRAWAL_RANKING = "Withdrawal Ranking";

    private final Locator rows;
    private final Locator saveButton;
    private final Locator cancelButton;

    public RankingAlertsSettingsPage(Page page) {
        super(page);
        this.rows = page.locator("table tbody tr");
        this.saveButton = page.getByRole(AriaRole.BUTTON, new Page.GetByRoleOptions().setName("Save changes"));
        this.cancelButton = page.getByRole(AriaRole.BUTTON, new Page.GetByRoleOptions().setName("Cancel").setExact(true));
    }

    public boolean isShowing() {
        return page.getByText("Ranking Alerts", new Page.GetByTextOptions().setExact(true)).count() > 0
                && rows.count() > 0;
    }

    private Locator row(String alert) {
        return rows.filter(new Locator.FilterOptions().setHasText(alert));
    }

    public boolean isOn(String alert) {
        Locator toggle = row(alert).locator("input[type=checkbox], [role=switch]");
        return toggle.count() > 0 && toggle.first().isChecked();
    }

    public void setOn(String alert, boolean on) {
        if (isOn(alert) != on) {
            CaseLog.step("Setting the \"" + alert + "\" alert " + (on ? "On" : "Off") + ".");
            row(alert).locator("input[type=checkbox], [role=switch]").first().click();
        }
    }

    public String whenItIsSent(String alert) {
        return cellOf(alert, 1);
    }

    public String dataCardShownToMember(String alert) {
        return cellOf(alert, 2);
    }

    private String cellOf(String alert, int column) {
        Locator target = row(alert);
        if (target.count() == 0) {
            return "";
        }
        Locator cell = target.first().locator("td").nth(column);
        return cell.count() == 0 ? "" : cell.innerText().trim();
    }

    /** Saves and returns what the page said, OK pressed - "" when nothing appeared. */
    public String save() {
        CaseLog.step("Clicking Save changes.");
        saveButton.click();
        return PromptMessage.readAndClose(page, 4000);
    }

    public void cancel() {
        CaseLog.step("Clicking Cancel.");
        cancelButton.click();
    }
}
